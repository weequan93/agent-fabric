import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {decodeMeasurement} from '../../../../g1-storage/scripts/measurement-transport.mjs';
const base=new URL('./',import.meta.url);
const lines=readFileSync(new URL('controller/job-cc21a2b995/f05-02.authority-component/stdout.log',base),'utf8').trim().split('\n');
const rows=lines.filter(l=>l.startsWith('{')).map(l=>JSON.parse(l));
const frames=rows.filter(r=>r.measurement==='storage-measurement-transport'&&r.binding?.phase==='command');
assert.equal(frames.length,4);assert.equal(frames.at(-1).kind,'final');
const final=frames.at(-1),receipt=rows.filter(r=>r.measurement==='storage-measurement-transport'&&r.digest===final.digest);
const decoded=decodeMeasurement(receipt,final.binding);
writeFileSync(new URL('authority-command-decoded.json',base),decoded.raw);
const observations=rows.filter(r=>['storage-owned-fixture','storage-container-cleanup','storage-root-cleanup','storage-test-report'].includes(r.measurement));
assert(observations.some(r=>r.measurement==='storage-owned-fixture'&&r.loopback&&r.paidCallsAllowed===false));
assert(observations.some(r=>r.measurement==='storage-container-cleanup'&&r.removed&&r.censusUnchanged));
assert(observations.some(r=>r.measurement==='storage-root-cleanup'&&r.removed));
const report=observations.find(r=>r.measurement==='storage-test-report');assert(report);assert.equal(report.reports[0].tests,118);
writeFileSync(new URL('authority-resource-observations.json',base),JSON.stringify(observations,null,2)+'\n');
console.log(JSON.stringify({bytes:decoded.raw.length,sha256:'sha256:'+createHash('sha256').update(decoded.raw).digest('hex'),tests:report.reports[0].tests,innerOwnershipCleanupObserved:true,outerSupervisorQualified:false,productQualification:false}));
